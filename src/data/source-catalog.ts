export type SourceTier = 'S' | 'A' | 'B' | 'C';
export type SourceKind = 'ATS' | 'GLOBAL' | 'TECH' | 'REMOTE' | 'CONTRACT' | 'PUBLIC' | 'REGIONAL';
export type SourceState =
  'ADAPTER_IMPLEMENTED' | 'READY_TO_BUILD' | 'NEEDS_API_KEY' | 'NEEDS_COMPANY_SEEDS' | 'RESEARCH_ONLY';

export type SourceCatalogItem = {
  id: string;
  name: string;
  regions: string[];
  kind: SourceKind;
  tier: SourceTier;
  state: SourceState;
  remoteSupport: boolean;
  contractSupport: boolean;
  urlPattern?: string;
};

const slug = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const add = (
  names: string,
  regions: string[],
  kind: SourceKind,
  tier: SourceTier,
  state: SourceState,
  remoteSupport = true,
  contractSupport = false,
) =>
  names.split(';').map<SourceCatalogItem>((name) => ({
    id: slug(`${kind}-${name}`),
    name,
    regions,
    kind,
    tier,
    state,
    remoteSupport,
    contractSupport,
  }));

